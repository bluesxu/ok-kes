def apply(task, order):
    """按 order 重排 default_config，标记隐藏项和子选项，补全说明。没列进 order 的项放在最后。"""
    old = dict(task.default_config)
    task.default_config.clear()
    for key in ("_enabled", *order):
        if key in old:
            task.default_config[key] = old.pop(key)
    task.default_config.update(old)

    config_type = task.config_type
    for key in HIDDEN_KEYS:
        if key in task.default_config:
            config_type.setdefault(key, {})["hidden"] = True
    for key, children in SUB_CONFIGS.items():
        present = [child for child in children if child in task.default_config]
        if key in task.default_config and present:
            config_type.setdefault(key, {})["sub_configs"] = {True: present}
    for key, text in DESCRIPTIONS.items():
        if key in task.default_config and not task.config_description.get(key):
            task.config_description[key] = text
